"""Telegram auto-responder.

Commands (owner only, if OWNER_ID is set):
  /watch @username [reply text]  - auto-answer messages from that username
  /unwatch @username             - stop answering that username
  /list                          - show watched usernames
  /help

Env: BOT_TOKEN (required), OWNER_ID (optional), ANTHROPIC_API_KEY (optional,
replies are generated by Claude; otherwise the fixed reply text is used).
"""
import json, os, sys, time, urllib.request, urllib.error

TOKEN = os.environ["BOT_TOKEN"]
OWNER_ID = int(os.environ["OWNER_ID"]) if os.environ.get("OWNER_ID") else None
API = f"https://api.telegram.org/bot{TOKEN}/"
STATE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "watched.json")
DEFAULT_REPLY = "Hi! I'm away right now and will get back to you soon."
MODEL = os.environ.get("CLAUDE_MODEL", "claude-sonnet-5-5")


def call(method, **params):
    req = urllib.request.Request(API + method, json.dumps(params).encode(),
                                 {"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=70) as r:
            return json.load(r)["result"]
    except urllib.error.HTTPError as e:
        print("API error", method, e.read().decode(), file=sys.stderr)
        return None


def load():
    try:
        with open(STATE) as f:
            return json.load(f)
    except FileNotFoundError:
        return {}


def save(d):
    with open(STATE, "w") as f:
        json.dump(d, f)


def ai_reply(text, instructions):
    key = os.environ.get("ANTHROPIC_API_KEY")
    if not key:
        return instructions or DEFAULT_REPLY
    system = ("You are replying on behalf of the account owner in Telegram. "
              "Be brief and friendly. " + (f"Owner's instructions: {instructions}" if instructions else ""))
    body = {"model": MODEL, "max_tokens": 300, "system": system,
            "messages": [{"role": "user", "content": text}]}
    req = urllib.request.Request("https://api.anthropic.com/v1/messages", json.dumps(body).encode(),
                                 {"x-api-key": key, "anthropic-version": "2023-06-01",
                                  "content-type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)["content"][0]["text"]
    except Exception as e:
        print("Claude error", e, file=sys.stderr)
        return instructions or DEFAULT_REPLY


def handle(msg):
    text = msg.get("text", "")
    chat_id = msg["chat"]["id"]
    sender = msg.get("from", {})
    uname = (sender.get("username") or msg["chat"].get("username") or "").lower()
    watched = load()

    if text.startswith("/"):
        cmd, _, rest = text.partition(" ")
        cmd = cmd.split("@")[0].lower()
        if OWNER_ID and sender.get("id") != OWNER_ID and cmd in ("/watch", "/unwatch", "/list"):
            return call("sendMessage", chat_id=chat_id, text="Not allowed.")
        if cmd == "/watch":
            parts = rest.strip().split(None, 1)
            if not parts:
                return call("sendMessage", chat_id=chat_id, text="Usage: /watch @username [instructions or fixed reply]")
            u = parts[0].lstrip("@").lower()
            watched[u] = parts[1] if len(parts) > 1 else ""
            save(watched)
            call("sendMessage", chat_id=chat_id, text=f"Now auto-answering @{u}.")
        elif cmd == "/unwatch":
            u = rest.strip().lstrip("@").lower()
            watched.pop(u, None)
            save(watched)
            call("sendMessage", chat_id=chat_id, text=f"Stopped answering @{u}.")
        elif cmd == "/list":
            call("sendMessage", chat_id=chat_id,
                 text="Watching: " + (", ".join("@" + u for u in watched) or "nobody"))
        else:
            call("sendMessage", chat_id=chat_id,
                 text="/watch @username [reply/instructions]\n/unwatch @username\n/list")
        return

    if uname in watched and text:
        call("sendChatAction", chat_id=chat_id, action="typing")
        call("sendMessage", chat_id=chat_id, text=ai_reply(text, watched[uname]))


def setup():
    call("setMyDescription", description=(
        "I automatically answer messages from chats you choose. "
        "Use /watch @username to start answering that person, /unwatch to stop, /list to see who."))
    call("setMyShortDescription", short_description="Auto-answers messages from chosen usernames.")
    call("setMyCommands", commands=[
        {"command": "watch", "description": "Auto-answer a username: /watch @user [reply]"},
        {"command": "unwatch", "description": "Stop answering a username"},
        {"command": "list", "description": "Show watched usernames"},
        {"command": "help", "description": "Show help"}])


def main():
    setup()
    offset = None
    while True:
        updates = call("getUpdates", offset=offset, timeout=50) or []
        for u in updates:
            offset = u["update_id"] + 1
            if "message" in u:
                try:
                    handle(u["message"])
                except Exception as e:
                    print("handler error", e, file=sys.stderr)
        if not updates:
            time.sleep(1)


if __name__ == "__main__":
    main()
